"""The `app` schema migrations against an empty Postgres (NEU-2031, spec §7.3).

Alembic runs in-process, through the same `migrations/env.py` the CLI runs, pointed at a scratch
database through `Config.attributes`: the downgrade to base would otherwise empty the dev
database's crosswalk.
"""

import psycopg
import pytest
from alembic import command
from alembic.util import AutogenerateDiffsDetected

from tests.integration.conftest import alembic_config

# (column, type, nullable) in table order, as information_schema reports them.
EXPECTED_COLUMNS = {
    "adjudication": [
        ("cluster_fingerprint", "text", False),
        ("model", "text", False),
        ("prompt_version", "text", False),
        ("decision", "text", True),
        ("confidence", "numeric", True),
        ("reason", "text", True),
        ("decided_at", "timestamp with time zone", True),
    ],
    "crosswalk": [
        ("contributor_key", "text", False),
        ("donor_id", "bigint", False),
        ("assigned_at", "timestamp with time zone", True),
        ("build_id", "text", True),
    ],
    "donor_redirect": [
        ("old_donor_id", "bigint", False),
        ("donor_id", "bigint", False),
    ],
    "resolution_quality": [
        ("model_version", "text", False),
        ("cycle", "integer", False),
        ("scope", "text", False),
        ("dime_version", "text", False),
        ("top_limit", "integer", True),
        ("contribution_rows", "bigint", False),
        ("matched_rows", "bigint", False),
        ("labelled_keys", "bigint", False),
        ("correct_pairs", "bigint", False),
        ("predicted_pairs", "bigint", False),
        ("true_pairs", "bigint", False),
        ("precision", "numeric", True),
        ("recall", "numeric", True),
        ("validated_at", "timestamp with time zone", False),
    ],
    "unmatched_filing": [
        ("cycle", "integer", False),
        ("candidate_id", "text", False),
        ("office", "text", True),
        ("state", "text", True),
        ("district", "text", True),
        ("seen_at", "timestamp with time zone", True),
    ],
}


def app_objects(conninfo: str) -> dict[str, set[str]]:
    """Every relation in `app`, by kind (`r` table, `S` sequence, `i` index)."""
    with psycopg.connect(conninfo) as conn:
        rows = conn.execute(
            "SELECT c.relkind, c.relname FROM pg_class c"
            " JOIN pg_namespace n ON n.oid = c.relnamespace WHERE n.nspname = 'app'"
        ).fetchall()
    objects: dict[str, set[str]] = {}
    for kind, name in rows:
        objects.setdefault(kind, set()).add(name)
    return objects


def test_upgrade_creates_exactly_the_app_tables_and_sequence(migrated_db: str) -> None:
    objects = app_objects(migrated_db)

    assert objects["r"] == {*EXPECTED_COLUMNS, "alembic_version"}
    assert objects["S"] == {"donor_id_seq"}
    assert "ix_crosswalk_donor_id" in objects["i"]


def test_columns_match_the_contract(migrated_db: str) -> None:
    with psycopg.connect(migrated_db) as conn:
        rows = conn.execute(
            "SELECT table_name, column_name, data_type, is_nullable = 'YES'"
            " FROM information_schema.columns"
            " WHERE table_schema = 'app' AND table_name <> 'alembic_version'"
            " ORDER BY table_name, ordinal_position"
        ).fetchall()
    columns: dict[str, list[tuple[str, str, bool]]] = {}
    for table, column, data_type, nullable in rows:
        columns.setdefault(table, []).append((column, data_type, nullable))

    assert columns == EXPECTED_COLUMNS


def test_donor_id_seq_starts_at_1(migrated_db: str) -> None:
    with psycopg.connect(migrated_db) as conn:
        row = conn.execute("SELECT nextval('app.donor_id_seq')").fetchone()

    assert row == (1,)


def test_adjudication_rejects_an_unknown_decision(migrated_db: str) -> None:
    with psycopg.connect(migrated_db) as conn, pytest.raises(psycopg.errors.CheckViolation):
        conn.execute(
            "INSERT INTO app.adjudication (cluster_fingerprint, model, prompt_version, decision)"
            " VALUES ('f', 'm', 'v1', 'maybe')"
        )


def test_resolution_quality_rejects_an_unknown_scope(migrated_db: str) -> None:
    with psycopg.connect(migrated_db) as conn, pytest.raises(psycopg.errors.CheckViolation):
        conn.execute(
            "INSERT INTO app.resolution_quality (model_version, cycle, scope, dime_version,"
            " contribution_rows, matched_rows, labelled_keys, correct_pairs, predicted_pairs,"
            " true_pairs, validated_at) VALUES ('m', 2024, 'all', '4.0', 0, 0, 0, 0, 0, 0, now())"
        )


def test_alembic_check_reports_no_drift(migrated_db: str) -> None:
    command.check(alembic_config(migrated_db))


def test_alembic_check_reports_a_missing_table(scratch_db: str) -> None:
    # Guards the guard: an include_name that filtered out `app` would pass any database.
    config = alembic_config(scratch_db)
    command.upgrade(config, "head")
    with psycopg.connect(scratch_db) as conn:
        conn.execute("DROP TABLE app.unmatched_filing")

    with pytest.raises(AutogenerateDiffsDetected, match="unmatched_filing"):
        command.check(config)


def test_downgrade_to_base_and_upgrade_again(migrated_db: str) -> None:
    config = alembic_config(migrated_db)

    command.downgrade(config, "base")
    assert app_objects(migrated_db).get("S") is None
    assert app_objects(migrated_db)["r"] == {"alembic_version"}

    command.upgrade(config, "head")
    assert app_objects(migrated_db)["r"] == {*EXPECTED_COLUMNS, "alembic_version"}
